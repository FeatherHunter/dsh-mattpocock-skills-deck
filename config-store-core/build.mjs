/**
 * config-store-core/build.mjs —— 配置读写核的编译脚本（#1012）
 *
 * 只转译不打包：用仓库现成的 esbuild 把 config-store-core/src/ 下每个 TS 文件
 * 一对一转成 src/shared/config-store/ 下的同名 JS；另跑 tsc --noEmit 只做类型检查。
 * 生成的 JS 提交到 git；改了 TS 没重新生成，tests/verify-config-store-freshness.js 会变红。
 *
 * 形态与 label-color-core/build.mjs 完全一致（三处要求同样适用）：
 * 1. 本文件导出 transpileUnit、runTypeCheck、buildAll 三个函数，外加 UNITS 清单，
 *    scripts/build.mjs 在一条命令里带上它，新鲜度门禁直接读 UNITS，不手抄。
 * 2. buildAll 先判断源码目录与 tsconfig 在不在。npm 发布包里没有这棵源码树
 *    （package/package.json 的 files 白名单里没有它），在那种子树里跑构建时
 *    跳过转译并打印一行提示，而不是把整个构建打断。
 * 3. 转译结果把 esbuild 收在文件末尾的 `export { ... };` 改写成声明前的行首 export。
 *
 * 用法：node config-store-core/build.mjs（在仓库根目录；日常更常用 node scripts/build.mjs，
 * 那条命令会把本脚本带进去一起跑）。
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import * as esbuild from 'esbuild'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC_DIR = resolve(ROOT, 'config-store-core/src')
const OUT_DIR = resolve(ROOT, 'src/shared/config-store')
const TSCONFIG = resolve(ROOT, 'config-store-core/tsconfig.json')

export const UNITS = [
  { ts: 'ports.ts', js: 'ports.js' },
  { ts: 'workspace.ts', js: 'workspace.js' },
  { ts: 'settings.ts', js: 'settings.js' },
  { ts: 'labels.ts', js: 'labels.js' },
]

function headerFor(tsName) {
  return `// AUTO-GENERATED by node config-store-core/build.mjs — DO NOT EDIT. Source: config-store-core/src/${tsName}\n`
}

/**
 * 把 esbuild 收在文件末尾的导出块改写成声明前的行首 export。
 *
 * 为什么必须改写：产物要同时满足两条——宿主半走普通相对 import，
 * 新鲜度门禁要求「要用的东西都带行首 export」（与其它核同一口径）。
 * esbuild 的转译结果是把声明照常写在前面、末尾收一个 `export { x, y };` 块，
 * 这里统一改回行首形式。找不到声明就抛错，绝不静默产出少导出的产物。
 */
function inlineExportDeclarations(code) {
  const clause = /(^|\n)export \{\n([\s\S]*?)\n\};\n?$/.exec(code)
  if (!clause) {
    if (/(^|\n)export \{/.test(code)) {
      throw new Error('[config-store-core] 转译结果里出现了没有预料到的导出块写法，拒绝改写：\n' + code.slice(-300))
    }
    return code
  }
  const names = clause[2]
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s !== '')
  let body = code.slice(0, clause.index) + (clause[1] === '\n' ? '\n' : '')
  for (const name of names) {
    if (!/^[A-Za-z_$][\w$]*$/.test(name)) {
      throw new Error(`[config-store-core] 导出块里有改不了名的条目「${name}」：本脚本只支持原样导出，不支持 as 改名`)
    }
    const decl = new RegExp('^(?:async )?function ' + name + '\\b|^(?:const|let|var) ' + name + '\\b|^class ' + name + '\\b', 'm')
    const hit = decl.exec(body)
    if (!hit) {
      throw new Error(`[config-store-core] 导出块里的名字「${name}」在这份文件里找不到声明，拒绝生成少一个导出的产物`)
    }
    body = body.slice(0, hit.index) + 'export ' + body.slice(hit.index)
  }
  return body
}

/** 与新鲜度门禁同一口径：转译加包头，换行归一，末尾恰好一个换行。 */
export function transpileUnit(tsName) {
  const tsPath = resolve(SRC_DIR, tsName)
  const source = readFileSync(tsPath, 'utf8')
  const out = esbuild.transformSync(source, {
    loader: 'ts',
    format: 'esm',
    // 保守目标：Node 宿主与浏览器闭包两边都跑得动。
    target: 'es2020',
  })
  const normalized = out.code.replace(/\r\n/g, '\n').replace(/\s+$/, '') + '\n'
  return headerFor(tsName) + inlineExportDeclarations(normalized)
}

/** 跑一次 `tsc --noEmit`。typescript 没装（没跑过 pnpm install）时明确报错，不静默跳过。 */
export function runTypeCheck() {
  const require = createRequire(resolve(ROOT, 'package.json'))
  let tscBin
  try {
    tscBin = resolve(dirname(require.resolve('typescript/package.json')), 'bin/tsc')
  } catch {
    throw new Error('[config-store-core] 找不到 typescript：请先运行 pnpm install（devDependencies 含 typescript）')
  }
  const r = spawnSync(process.execPath, [tscBin, '-p', TSCONFIG], { encoding: 'utf8' })
  if (r.status !== 0) {
    throw new Error(`[config-store-core] tsc --noEmit 未通过：\n${r.stdout || ''}${r.stderr || ''}`)
  }
  console.log('[config-store-core] tsc --noEmit 通过')
}

/**
 * 类型检查加转译，全部产物写进 src/shared/config-store/。
 * 源码目录或 tsconfig 不在时就跳过：发布包与 package/ 子树里本来就没有这棵源码树，
 * 那种情况下构建立刻中断会挡住别的步骤，而这里要的只是「这一步没法做，跳过它」。
 * 返回 { skipped, files }，调用方（scripts/build.mjs）可以据此打印自己的日志。
 */
export function buildAll() {
  if (!existsSync(SRC_DIR) || !existsSync(TSCONFIG)) {
    console.log('[config-store-core] 没找到源码目录或 tsconfig（' + SRC_DIR + ' / ' + TSCONFIG + '），本次跳过配置读写核的转译与类型检查。发布包与 package/ 子树里本来就没有这棵源码树，这是预期情况；要重新生成产物请在仓库根目录跑 node scripts/build.mjs。')
    return { skipped: true, files: [] }
  }
  runTypeCheck()
  mkdirSync(OUT_DIR, { recursive: true })
  const files = []
  for (const u of UNITS) {
    const text = transpileUnit(u.ts)
    const outPath = resolve(OUT_DIR, u.js)
    writeFileSync(outPath, text, 'utf8')
    console.log(`[config-store-core] ${u.ts} -> src/shared/config-store/${u.js}（${text.split('\n').length} 行）`)
    files.push('src/shared/config-store/' + u.js)
  }
  return { skipped: false, files }
}

const invoked = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invoked) {
  try {
    buildAll()
  } catch (e) {
    console.error((e && e.message) || e)
    process.exit(1)
  }
}
