/**
 * data/capability-entries.ts —— 162 条能力的「入口形态与落点」台账。
 *
 * 为什么要有这份台账：#1860 把页面壳收进原型后，162 条能力不再靠页尾那份长清单交代去向，
 * 每条能力必须能说出「点哪里进去、打开什么、结果落在哪」。四页签上的能力由页面自己画控件，
 * 二级页上的能力由能力行的演示按钮承接；这份文件把「每条能力落在哪种控件上」定下来，
 * 命令面板按它显示位置，检查脚本按它核对有没有漏掉的条目。
 *
 * 两侧怎么分工：
 *   - 四页签（改动 / 提交历史 / 工作区 / 储藏）的条目手写在下面：它们的入口形态要人拍板，
 *     有的是行内按钮、有的在行尾菜单、有的在提交选项里，不能从能力账本推出来。
 *   - 十二个二级页的条目由能力账本派生：页面底部的能力行本来就为每条能力画了一个演示按钮
 *     （只读条目画成只读说明），形态因此是统一的，再逐条手抄一遍只会和账本对不上。
 *
 * 状态只有四种取值：已画（这张票之前就有可点入口）、本票已画（#1876 补的）、
 * 待画（决定已经给出，由后续切片画）、只读（这类能力本来就不该有可改控件）。
 * 「待画」与「本票已画」必须写一句理由：为什么放这里，不放在另外两处。
 */
// 写全 .ts 后缀：这个文件除了被打进原型，还要被 tools/check-capability-entries.ts 用 Node 直接加载，
