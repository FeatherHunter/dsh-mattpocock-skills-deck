/** 四页签：这些条目手写在上面，其余的都落在二级页上。 */
const TAB_TARGETS = ['changes', 'commits', 'worktrees', 'stash']

/**
 * 全部 162 条：先用手写的四页签条目，再用能力账本补出二级页的那部分。
 * 只在模块加载时算一次——命令面板一屏要取几十条能力的位置，每次重算会把 162 条铺一遍。
 * 顺序跟能力账本一致，检查脚本与命令面板都按这个顺序读。
 */
const ALL_ENTRIES: CapabilityEntry[] = (() => {
  const handwritten = new Map(TAB_ENTRIES.map((entry) => [entry.id, entry]))
  return CAPABILITIES.map((cap) => handwritten.get(cap.id) ?? derivedEntry(cap))
})()

/** 编号到条目的索引：命令面板按编号取一条时不用再扫一遍全部条目。 */
const ENTRY_BY_ID = new Map(ALL_ENTRIES.map((entry) => [entry.id, entry]))

export function allCapabilityEntries(): CapabilityEntry[] {
  return ALL_ENTRIES
}

/** 一条能力的台账条目；能力账本里没有这个编号时返回 undefined。 */
export function capabilityEntryOf(id: string): CapabilityEntry | undefined {
  return ENTRY_BY_ID.get(id)
}

/**
 * 二级页条目：页面底部的能力清单为每条能力画了一个「演示这条流程」按钮，
 * 只读能力画的是只读说明。形态因此统一，落点写页面名就够。
 */
function derivedEntry(cap: Capability): CapabilityEntry {
  const page = PAGE_TITLES[cap.target] ?? cap.target
  if (cap.readOnly) {
    return {
      id: cap.id,
      form: cap.placement === '外' ? '面板之外' : '只读诊断',
      at: page + '页能力清单里的只读说明',
      status: '只读',
      reason: cap.placement === '外'
        ? '这条能力要面板之外的工具或平台才能做，页面只写清边界，不画半截按钮。'
        : '只读能力只展示它读到的形状，面板不提供执行按钮。',
    }
  }
  if (cap.target === 'platform') {
    return { id: cap.id, form: '页面动作', at: '平台与能力边界页的说明行', status: '已画' }
  }
  return { id: cap.id, form: '页面动作', at: page + '页能力清单里的「演示这条流程」', status: '已画' }
}

/** 四页签的编号集合：检查脚本用它确认手写条目没有漏。 */
export function tabCapabilityIds(): string[] {
  return CAPABILITIES.filter((cap) => TAB_TARGETS.includes(cap.target)).map((cap) => cap.id)
}

/** 每条手写条目：检查脚本用它对账本核对编号。 */
export function handwrittenEntries(): CapabilityEntry[] {
  return TAB_ENTRIES.slice()
}
