/** 一个二级页在管理索引卡片、页面标题、命令面板位置说明里的三套说法。 */
export interface PageMeta {
  id: PageId
  /** 页面标题，也是命令面板里的位置名（「分支与标签」）。 */
  title: string
  /** 管理索引卡片上的一句话：这一页能办成什么事。 */
  card: string
  /** 页面标题下面的一句导语：不重复标题，讲清这一页的边界与数据来源。 */
  lede: string
  /** 管理索引卡片右上角的数量说明：用采集到的真实数字，不写「若干」。 */
  count: string
  /** 是否整仓不可逆动作集中地：卡片与页头都要给危险提示。 */
  danger?: boolean
}

