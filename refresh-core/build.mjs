function headerFor(tsName) {
  return `// AUTO-GENERATED by node refresh-core/build.mjs — DO NOT EDIT. Source: refresh-core/src/${tsName}\n`
}

/** 源码树不在时那句提示。两个函数共用一份，免得两处措辞慢慢走岔。 */
function skipNotice(step) {
  return (
    '[refresh-core] 没找到源码目录或 tsconfig（' + SRC_DIR + ' / ' + TSCONFIG + '），本次跳过' + step +
    '。发布包与 package/ 子树里本来就没有这棵源码树，这是预期情况；要重新生成产物请在仓库根目录跑 node scripts/build.mjs。'
  )
}

/**
 * 把 esbuild 收在文件末尾的导出块改写成声明前的行首 export。
 *
 * 为什么必须改写：esbuild 的转译结果不是 `export const X = 1` 这种行首形式，而是把声明照常写在
 * 前面、末尾收一个 `export { X, Y };` 块。将来某个产物要拼进客户端闭包时，拼接的做法是去掉每行
 * 行首的 `export `（见 scripts/build.mjs 的 extractModuleBlock）；那种末尾块去掉行首 export 之后
 * 只剩一个 `{ X, Y };` 语句块，名字虽然还在（函数声明与 const 都在同一作用域里），形态却与仓库里
 * 其它拼进闭包的共享文件完全不一样，读代码的人会看不懂。所以这里统一改回行首形式。
 *
 * 只认「名字能在同一份文件里找到 function / const / let / var / class 声明」这一种情形；
 * 找不到就抛错，绝不静默产出一个少了一个导出的产物。
 */
function inlineExportDeclarations(code) {
  const clause = /(^|\n)export \{\n([\s\S]*?)\n\};\n?$/.exec(code)
  if (!clause) {
    if (/(^|\n)export \{/.test(code)) {
      throw new Error('[refresh-core] 转译结果里出现了没有预料到的导出块写法，拒绝改写：\n' + code.slice(-300))
    }
    return code
  }
  const names = clause[2]
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s !== '')
  let body = code.slice(0, clause.index) + (clause[1] === '\n' ? '\n' : '')
  for (const name of names) {
    if (!/^[A-Za-z_$][\w$]*$/.test(name)) {
      throw new Error(`[refresh-core] 导出块里有改不了名的条目「${name}」：本脚本只支持原样导出，不支持 as 改名`)
    }
    const decl = new RegExp('^(?:async )?function ' + name + '\\b|^(?:const|let|var) ' + name + '\\b|^class ' + name + '\\b', 'm')
    const hit = decl.exec(body)
    if (!hit) {
      throw new Error(`[refresh-core] 导出块里的名字「${name}」在这份文件里找不到声明，拒绝生成少一个导出的产物`)
    }
    body = body.slice(0, hit.index) + 'export ' + body.slice(hit.index)
  }
  return body
}

/** 与新鲜度门禁同一口径：转译加包头，换行归一，末尾恰好一个换行。 */
export function transpileUnit(tsName) {
  const tsPath = resolve(SRC_DIR, tsName)
  const source = readFileSync(tsPath, 'utf8')
  const out = esbuild.transformSync(source, {
    loader: 'ts',
    format: 'esm',
    // 保守目标：Node 宿主与浏览器闭包两边都跑得动。
    target: 'es2020',
  })
  const normalized = out.code.replace(/\r\n/g, '\n').replace(/\s+$/, '') + '\n'
  return headerFor(tsName) + inlineExportDeclarations(normalized)
}

/**
 * 跑一次 `tsc --noEmit`。typescript 没装（没跑过 pnpm install）时明确报错，不静默跳过。
 * 源码树或 tsconfig 不在时跳过并打印一行提示（见文件头的第 3 条差别）。
 * 返回 { skipped }，调用方据此知道这一步做了没有。
 */
export function runTypeCheck() {
  if (!existsSync(SRC_DIR) || !existsSync(TSCONFIG)) {
    console.log(skipNotice('类型检查'))
    return { skipped: true }
  }
  const require = createRequire(resolve(ROOT, 'package.json'))
  let tscBin
  try {
    tscBin = resolve(dirname(require.resolve('typescript/package.json')), 'bin/tsc')
  } catch {
    throw new Error('[refresh-core] 找不到 typescript：请先运行 pnpm install（devDependencies 含 typescript）')
  }
  const r = spawnSync(process.execPath, [tscBin, '-p', TSCONFIG], { encoding: 'utf8' })
  if (r.status !== 0) {
    throw new Error(`[refresh-core] tsc --noEmit 未通过：\n${r.stdout || ''}${r.stderr || ''}`)
  }
  console.log('[refresh-core] tsc --noEmit 通过')
  return { skipped: false }
}

/**
 * 把每个 TS 文件逐份转译进 src/shared/refresh/。类型检查不在这里，由调用方先调 runTypeCheck。
 * 源码目录或 tsconfig 不在时跳过：发布包与 package/ 子树里本来就没有这棵源码树，
 * 那种情况下构建立刻中断会挡住别的步骤，而这里要的只是「这一步没法做，跳过它」。
 * 返回 { skipped, files }，调用方（scripts/build.mjs）可以据此打印自己的日志。
 */
export function buildAll() {
  if (!existsSync(SRC_DIR) || !existsSync(TSCONFIG)) {
    console.log(skipNotice('转译'))
    return { skipped: true, files: [] }
  }
  mkdirSync(OUT_DIR, { recursive: true })
  const files = []
  for (const u of UNITS) {
    const text = transpileUnit(u.ts)
    const outPath = resolve(OUT_DIR, u.js)
    writeFileSync(outPath, text, 'utf8')
    console.log(`[refresh-core] ${u.ts} -> src/shared/refresh/${u.js}（${text.split('\n').length} 行）`)
    files.push('src/shared/refresh/' + u.js)
  }
  return { skipped: false, files }
}

const invoked = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invoked) {
  try {
    runTypeCheck()
    buildAll()
  } catch (e) {
    console.error((e && e.message) || e)
    process.exit(1)
  }
}
