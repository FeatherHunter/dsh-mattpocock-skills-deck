/**
 * refresh-core/build.mjs —— 刷新核心的编译脚本（#720 落地）
 *
 * 只转译不打包：用仓库现成的 esbuild 把 refresh-core/src/ 下每个 TS 文件一对一转成
 * src/shared/refresh/ 下的同名 JS；另跑 tsc --noEmit 只做类型检查。生成的 JS 提交进 git；
 * 改了 TS 没重新生成，tests/verify-refresh-freshness.js 会变红。
 *
 * 与 update-core/build.mjs 的差别，都是这份形态的要求，不是随手改的
 * （依据：docs/adr/20260913-builtin-ts-shape.md §2.4 点名要补的那个缺口）：
 * 1. 本文件导出 transpileUnit、runTypeCheck、buildAll 三个函数。update-core 的脚本只导出了
 *    transpileUnit，转译入口是文件内的私有函数、外面调不到；这里要让 scripts/build.mjs 在一条
 *    命令里把类型检查与转译都带上，所以三个都导出。
 * 2. 类型检查与转译是两步，调用方按顺序各调一次：本文件末尾的命令行入口与 scripts/build.mjs
 *    都是「先 runTypeCheck()，再 buildAll()」。为什么不照 label-color-core 那样把类型检查写在
 *    buildAll 里面：接线要求正是「runTypeCheck() 与 buildAll() 各调用一次」，写在里面会让一次
 *    主构建跑两遍 tsc，白等一秒；所以这里把两件事拆开，buildAll 只管判断源码树在不在、再把
 *    文件逐份转出来。谁要单独用 buildAll，记得自己先调 runTypeCheck。
 * 3. 两个函数都先判断源码目录与 tsconfig 在不在，不在就打印一行提示、跳过自己这一步，
 *    绝不中断整个构建。原因：npm 发布包里没有这棵源码树（package/package.json 的 files
 *    白名单只有 lib、shared、cordis.patch.yml、bundled-skills、scripts/），在那种子树里
 *    跑构建时这两步本来就做不了。
 * 4. 转译结果要把 esbuild 收在文件末尾的 `export { ... };` 改写成声明前的行首 export
 *    （见下面 inlineExportDeclarations 的说明）。这样产物形态与两份先例一致；将来真要把某个
 *    产物拼进客户端闭包时，拼接那套「去掉行首 export」的做法直接就能用，不必再改这个脚本。
 *
 * 用法：node refresh-core/build.mjs（在仓库根目录；日常更常用 node scripts/build.mjs，
 * 那条命令会把本脚本的这两步一起带上，不必手动补跑）。
 */
