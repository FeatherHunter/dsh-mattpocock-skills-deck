// projection/read-step.ts —— 读投影事务内的步骤钩子（只给门禁用）。
//
// 为什么要有它：要证明「一次投影的版本与数据来自同一个库快照」，必须让另一条连接正好在
// 投影读到一半时提交一笔真写。没有确定的插入点，门禁只能靠 sleep 去撞那个窗口 —— 那既不确定，
// 也会随机器快慢时红时绿。钩子给出的是一个稳定名字（例如 'list-after-rows'），投影在事务内、
// 完成某几条查询之后调一次；生产代码从不传它，所以它对线上行为零影响。
//
// 约定：stage 名字是对外契约的一部分，门禁按字面量比对，改名要同时改门禁，不要只改一边。
// 反例：不要在这个钩子里做任何生产需要的事情 —— 它存在的前提就是「线上没人传」。

/** 投影在事务内报出的步骤名；只收一个字符串，不把查询结果交出去（避免门禁顺手依赖内部形状）。 */
export type ReadStepHook = (stage: string) => void

/**
 * 调一次步骤钩子。没传就什么都不做；钩子自己抛错时让错误照常冒出去 ——
 * 门禁注入的那一笔写失败时必须当场变红，而不是被吞掉之后留下一条永远为真的断言。
 */
export function reportReadStep(hook: ReadStepHook | null | undefined, stage: string): void {
  if (typeof hook === 'function') hook(stage)
}
