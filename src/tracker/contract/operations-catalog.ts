/**
 * 3 条定位口：把「一个目录 / 一个仓库 / 一个票号」翻成身份与地址。
 *
 * 它们与操作的区别只有一条，但很要紧：**它们没有「我不支持」这种答案**。
 * 问「这个仓库在这个后端上叫什么」，答案是名字或者空；空也是答案，不是失败。
 * 所以注册表不替它们补桩，缺席就按缺席处理，调用方拿空值继续往下走（不抛、不拦）。
 *
 * `getRepoKey` 回 `{ owner, name }` 或 `null`（解析不出来就是 null，不是异常）；真起 gh 的那一级
 * 在同一个对象上带可选 `usage`，把这一笔出站交给会话管线记账（#1453）；
 * `describe` 回仓库身份；`issueAddress` 回一张票的地址——远端两家回网址，本地文件后端**算不出**
 * 票的地址（票文件名里那段标题后缀要读文件才知道），诚实回空串（#1144）。
 * 名字用「地址」不用「网址」：路径也是地址，本地这一家曾经给的就是票文件路径，
 * 说成「网址」会把本地那一家说成例外。
 */
export const LOCATORS = [
  'getRepoKey',
  'describe',
  'issueAddress',
] as const

/**
 * 26 条能力的上限：上面两段合起来。
 *
 * 这就是 `Tracker` 接口的全部成员，也是「一个后端最多能被要求做哪些事」的完整答案。
 * 门禁拿它逐条核对契约文件里有没有对应的成员声明，少一条判红。
 */
export const CAPABILITIES = [...OPERATIONS, ...LOCATORS] as const
