// src/shared/refresh-workspace-key.js —— 闸那一侧的工作区钥匙（短散列）单源。
//
// 这是什么：把「一个工作区根」折成一把短钥匙（8 位十六进制小写字母数字），宿主那道刷新闸按它
// 记活跃、记失败次数、记限流标记、记推迟队列。仓库里同一个工作区在闸里必须只有一格 —— 两把钥匙
// 就会把同一个工作区的账拆成两份记（#723 的「标活跃一格、过闸另一格」就是这么栽的：写事件那一路
// 的每一笔都被判「不在活跃集合里」而推迟，接线看起来接上了，生产里一次都发不出去）。
//
// 为什么单开一份共享文件的实现、而不是写在宿主某个文件里：宿主要用它的有三处 ——
//   · src/host/refresh/wiring.js（活跃集合、写事件白名单、七个 deck_* 工具、行级增量那一半）；
//   · src/host/detectChain.js（检查链求值那一笔记账的钥匙）。
// 宿主层的文件之间不许互相引用（tests/verify-no-same-layer-import.js），而宿主入口 src/host/index.js
// 已经贴着 350 行上限、没法再把这一份依赖注入给链那一侧。所以「算钥匙」这件事落在共享层一处，
// 宿主两侧各自从这一个文件取（宿主引用共享层是允许的方向）。
//
// 纪律（改这里的人先看这三条）：
//   1. **输入必须是已经洗过的工作区根** —— 也就是宿主既有出口 canonicalKey 的产物
//      （src/host/workspaceKey.js 的规整 + 锚到工作区根那一整套）。本函数只做最后一步散列，
//      自己不做任何归一：这里再洗一遍就会和宿主那支洗衣机洗出不同的字符串
//      （那支把 Windows 的盘符小写化并保留反斜杠，共享层这把 keyOf 洗出的是正斜杠形态），
//      于是同一格会裂成两格 —— 那正是本文件要防的事。
//   2. **同一个根只许有一把钥匙**：任何「按工作区过闸」的地方都要调这个函数，不许再抄一份散列。
//   3. **只用于内存表与日志字段**：它不进任何白名单文件、不落盘成用户可见的数据。
//
// 形状：'0000000' + 散列值十六进制，取末 8 位（与仓库其它地方的短散列同款）。
export function hash8(text) {
  try {
    const t = String(text || '')
    let h = 5381
    for (let i = 0; i < t.length; i++) h = (((h << 5) + h + t.charCodeAt(i)) >>> 0)
    return ('0000000' + h.toString(16)).slice(-8)
  } catch (e) { return '00000000' }
}

/**
 * 工作区根 → 闸里那一格的钥匙。
 * @param {string} root 已经洗过的工作区根（canonicalKey 的产物）
 * @returns {string} 8 位十六进制小写短散列
 */
export function workspaceKeyOf(root) {
  return hash8(String(root || ''))
}
