/**
 * src/shared/op-id.ts —— 操作编号（opId）的生成处。
 *
 * 为什么要有这一格：一趟操作会在日志里落成两层行——宿主那层说「调了哪条电话、成没成、花了多久」，
 * 房间那层说「里面起了哪几条外部命令、各走哪一支」。两层各记各的，排查时只能按时间戳排；
 * 同一时间有几趟并行就分不清谁是谁。宿主起一趟时生成一个编号随上下文递下去，房间把它抄进自己的行，
 * 两层就能靠一个键对上（这一格的契约见 src/tracker/contract/contexts.ts 的 OpContext.opId）。
 *
 * 形状与 deck 工具那条路（src/deck/tools/tracker-session.ts 的 newDeckOpId）一致：
 * 「十进制毫秒时间戳-自增序号的 36 进制」，例如 `1793118739614-1`。
 * 为什么用自增序号而不是随机短串：同一毫秒里的两趟也必须不重号，序号天然保证这一点；
 * 随机串有概率撞号，一撞号日志里两趟就串成了一趟，比没有编号更糟。
 * 两条路各持一份计数器，格式相同、取值各自独立——这不是「两份实现」，是同一格式的两个生成者；
 * 谁要改这个格式，必须两条路一起改，否则日志里会同时出现两种编号，按编号串行的排查就断了。
 *
 * 边界：本文件只做「生成编号」这一件事。不读配置、不碰日志、不引 refresh / tracker 任何一层——
 * tracker 层直接 import 它，从这里往上引一层就会把依赖方向倒过来。
 */

/** 这个进程里已经发出过几号（模块级：同一进程内递增，跨调用不重号）。 */
let seq = 0

/**
 * 生成一个操作编号：`<毫秒时间戳>-<序号 36 进制>`。
 * now 可注入假时钟（门禁要断言同一毫秒内发两个编号也不重号）。
 * 时钟读不出来时回 `op-<序号>`：宁可少一截时间信息，也不能因为时钟抛错就让调用方拿不到编号。
 */
export function newOpId(now?: () => number): string {
  const clock = typeof now === 'function' ? now : Date.now
  try { return String(clock()) + '-' + (++seq).toString(36) } catch { return 'op-' + (++seq).toString(36) }
}
