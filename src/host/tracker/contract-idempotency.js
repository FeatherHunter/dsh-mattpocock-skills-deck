/**
 * 创建幂等锚（`create(repo, input, ctx)` 上的可选输入字段 `input.idempotencyKey`）。
 *
 * 要解决的问题只有一句：**票已经建成了，只是调用方没收到回答**。超时、EOF、退出码非 0
 * 却已经写进去了 —— 这几种都会让外层重试，重试就再建一张，同一个逻辑动作在盘上变成两张票，
 * 而两次调用都回 ok（对抗式审查里真机复现过这条，见 docs/reviews/deck-tools-adversarial-review.md 的攻击场景一）。
 *
 * 契约答应的三件事：
 *  1. **锚要落到票面上**，是票面正文里的一行稳定标识（前端渲染后看不见），不是记在内存表里：
 *     GitHub 与 GitLab 写在正文（description）里，本地 Markdown 写在票文件里。
 *  2. **建后必须按锚回查**，而且回查读的是票面上的锚：不能只看这一次调用内存里的表 ——
 *     进程重启、插件重载、换一个会话回来之后，内存表没了、票还在，那种情况下才最需要它。
 *  3. **同一个锚提交两次，只多出一张票、返回同一个 key**，第二次不改、不重写那张票。
 *
 * 语义细节（每一条都有对应的自动检查，见 tests/tracker-contract/sections/idempotency.js）：
 *  - `idempotencyKey` 是**可选字段**：不传时的行为与加这个字段之前一模一样（每次都新建，
 *    这是既有行为，不许被改坏 —— 调用方自己承担重复建票的风险）。
 *  - 键只允许字母、数字、点、下划线、连字符、冒号、斜杠，最长 200 个字符。不合规就当场失败
 *    （parse 档），不「清洗」成另一个键：换掉之后写下去的键与调用方手里那个不是同一个串，
 *    第二次提交算不算同一个锚就成了运气问题。
 *  - 回查**找到了**那张票：直接把它交回去（返回同一个 key），不再发写请求、不再改文件。
 *  - 回查**没找到**：照常建票，并把锚写进新建的票面。
 *  - 回查**拿不准**（搜索接口报错、列表翻不完、目录读不出来）：**如实失败，绝不建票**。
 *    把「拿不准」当成「没找到」正是重复建票的来路，而且是在看起来成功了的外表下发生的。
 *    这一档的 error.kind 是 unsupported，message 里说清是「回查没能做成」而不是「已经建过」。
 *  - 命中复用的那张票必须**还开着**：已关闭的票不算命中（一个锚对应一件要做完的事，
 *    它已经做完了还拿旧 key 回来时，调用方要的是这次新建，旧票的结束状态归它自己去查）。
 *  - 锚回查**不新增操作、不升 CONTRACT_VERSION**：创建还是那一条 create，锚只是它的一个可选输入，
 *    没实现锚的后端由注册表按 OPERATIONS 自动补桩那套照旧（本票没有改 OPERATIONS 一个名字）。
 *
 * 今天三个后端的落实情况（各自由本票的探针盯着，做不到的那一档必须诚实说出来）：
 *  - 本地 Markdown：锚写在票文件里，回查就在这个工作区的票文件里按锚找（票就是文件，最直接）。
 *  - GitHub：锚写在正文里，回查走搜索接口（`gh search issues --match body`）。
 *    **已知边界**：GitHub 的正文搜索索引是异步建的，刚建完的那几十秒里搜索可能还搜不到那张票，
 *    所以「建完后马上重试」这个窗口**不能保证**被锚挡住；搜索搜不到时会退一步按
 *    「列出这个仓库最近更新的票、逐张读正文比对」（不依赖索引）。这一条是 GitHub 接口本身的性质，
 *    不是实现挑的省事做法，如实写在这里。
 *  - GitLab：锚写在 description 里，回查走 issues 接口的 `search` + `in=description`；
 *    这条接口同样受服务端搜索实现影响，拿不准时按上面「如实失败」那一档处理。
 */

