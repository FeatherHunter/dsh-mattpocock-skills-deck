// ─────────────────────────────────────────────────────────────────────────────
// 分页契约（#690 新加，2026-09-22）
//
// 为什么要有它：已关闭的票在首屏只装最近一百条（规格第 6.3 节），用户真要翻到更早的票时，得有办法按页
// 向后端要 —— 而不是把整个历史拉进内存。这条操作就是那个口子：**一次要一页行数据，外加「一共多少张」**。
//
// 语义：
//  - **排序键固定为「创建时间倒序」**（CREATED_AT DESC），调用方没得选。理由是翻页的稳定性：翻页期间
//    若有别的票被更新，按更新时间排序会让票在页与页之间挪位置，早先看过的那一页会漏掉一张；创建时间
//    是写下来就不动的，翻到哪一页都稳定。界面要按别的键排，是在**已加载的这些行**里排（规格第 13 节
//    也把「筛选与排序下推后端」列为不做的事）。
//  - **cursor 是不透明字符串**，调用方只负责原样回传、不许自己解析或拼装：GitHub 用它自己的 GraphQL
//    游标（`after`），GitLab 用页码，本地 Markdown 用票文件列表的下标。第一页传空串或不传。
//  - **limit 缺省 50、上限 200**：要得比上限多就按上限给（不是报错），返回的 items 条数如实反映实际
//    取到的张数（取到几张就是几张，不许多给也不许少给）。
//  - **total 是同一口径下的总数**：与这次调用的 filter 同一套筛选（口径与 counts 那条操作一致），
//    界面拿它写「已加载 x / 共 N」里的 N。它**不是**「还有多少页」的承诺：翻页期间有人关票，
//    这个数会动，界面按最近一次拿到的数显示即可。
//  - **items 是薄片段的行数据**：只带「画成列表里一行」与「列表这条流水线」用得上的字段
//    （清单见底稿 research/677-field-consumption.md 第 6 节：编号、标题、状态、创建与更新时间、标签、
//    指派人、作者、被阻塞引用、是否拉取请求、链接）。**不带正文、不带评论** —— 首屏那 11 MB 里
//    最大的一块就是正文与评论（规格第 14 节实测），而画一行一个字都用不到它们；点开单票详情时另有
//    一次自己的取数（那也是详情页兜底口径改成「还没拿到」的原因，见 #693）。
//    行上仍然要带 `parentKey` 这类今天没有读者的字段吗？不带 —— 底稿第 6.2 节列了这份「确定可以不带」
//    的清单。**但有三样必须补**（底稿第 6.3 节）：`number`、大写的 `state`、对象形状的 `labels[]`，
//    这三样是宿主在今天那条链上补的，页数据这条链也要在宿主侧同样补上，否则点行会压进 undefined、
//    已关闭票会被当成未关闭、改色补丁会静默失效。补在哪一层由宿主决定（见 src/host/issuePage.js）。
//  - **失败语义与 counts 那条一致**：unsupported（这个后端没实现）/ rate-limit / network / auth / parse。
//    拿不全就整体失败，不许返回半页 —— 界面上半页与一页长得一模一样，用户只会以为「历史就到这儿了」。
//  - **游标失效是单独一条要认得出的情况**：后端数据大改、进程重启之后，早先那个 cursor 可能已经指不到
//    东西。这时返回 parse 或 not-found，并且 message 里要说清「游标已失效，请重新加载」——界面据此
//    丢掉手上的游标、重取第一页，而不是把这一页当成历史翻到了头。
//  - **不缓存判定**（G5 红线，与 getDependencies / counts 同例）：失败（含「做不到」的桩）不进缓存。
//  - **不升 CONTRACT_VERSION**：这一次同样是纯新增操作，没实现它的后端由注册表自动补桩兜住，
//    既有形状与既有后端一个都没改。（写在这里，免得以后有人看见「契约加了东西却没升版号」再查一遍。）
//
// 谁在调它：宿主电话 wf.issuesPage（规格第 7.1 节），客户端那三个触发点（展开折叠行、状态筛选切到
//   「已关闭」、已加载区滚到底）走同一条路，共用同一份页数据与游标（规格第 7.4 节）。
// ─────────────────────────────────────────────────────────────────────────────

