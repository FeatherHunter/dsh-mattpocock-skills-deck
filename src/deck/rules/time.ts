// src/deck/rules/time.ts —— 纯规则侧的时钟口径（#1039 按 #1038 定版：纯侧不读钟）
//
// 为什么单独有这一件：纯规则要算「同一个 5 分钟窗口里的重试」，就必须知道现在是几毫秒，
// 但读钟本身是碰外面（#1038 定版：「纯度用严档，时钟等待都算碰外面」）。两条合起来的写法
// 只有一个：**时间从形参进来，纯规则一个字节都不读钟**。这一件把这条约定写成类型，
// 后来人想加一个 `Date.now()` 兜底时，编译期门禁（tests/verify-deck-rules-purity.js 与
// 本目录的 tsconfig.json）会当场把它拦下来，不靠人记得。
//
// 时间单位只有一种：Unix 毫秒（与 `Date.now()` 的返回值同一个刻度）。写成数字而不是
// 品牌类型，是为了让宿主侧注入真钟时不必做任何包装与断言 —— 这个目录里既没有 Date，
// 也就不会有人误把「秒」当「毫秒」传进来之外的第二类错误。

/** 一次调用的时刻，Unix 毫秒。由宿主侧注入（真钟或测试里的假时钟），纯规则只读不算。 */
export type Timestamp = number

/**
 * 拿一个「可能是时刻」的未知值收口成时刻：有限数字才算数，其余一律回 null。
 * 为什么收口放在这里而不是每处自己判：进来的值来自运行时（依赖袋、后端回包、测试夹具），
 * 形状不可信；把判断写在一处，各处读到的口径才不会各写一份。
 * 回 null 而不是回 0：0 是一个合法的时刻，混进来会让调用方分不清「没给」与「给了零点」。
 */
export function toTimestamp(v: unknown): Timestamp | null {
  return (typeof v === 'number' && Number.isFinite(v)) ? v : null
}
