// 派生目录不进扫描：构建产物、临时目录里的 .js 不是手写代码。
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'build', 'generated', '.scratch', 'coverage', 'tmp', 'artifacts'])
// 带这个头的文件由构建生成（例如 src/tracker/contract/vocabulary.js），不按手写源码判。
// 派生文件（scripts/build.mjs 生成的同名 .js）第一行就是 AUTO-GENERATED 横幅，形如
// `// AUTO-GENERATED by node scripts/build.mjs (pixel-ts) — DO NOT EDIT. Source: kernel/api-io.ts`。
// 注意只认「第一行就是横幅」：手写源码在正文里提到这个词（例如 api-io.ts 的说明注释）不能被当成
// 派生文件跳过 —— 那会让一整份源码从门禁里消失，是最危险的一种假绿。
const DERIVED_HEAD = /^\s*\/\/[ \t]*AUTO-GENERATED/

function walk(relDir) {
  const out = []
  const abs = path.join(ROOT, relDir)
  if (!fs.existsSync(abs)) return out
  const stack = [abs]
  while (stack.length) {
    const dir = stack.pop()
    let entries = []
    try { entries = fs.readdirSync(dir, { withFileTypes: true }) } catch { continue }
    for (const e of entries) {
      const full = path.join(dir, e.name)
      if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) stack.push(full); continue }
      if (!/\.(ts|js|mjs|cjs)$/.test(e.name)) continue
      if (/\.d\.ts$/.test(e.name)) continue
      out.push(path.relative(ROOT, full).split(path.sep).join('/'))
    }
  }
  return out.sort()
}

/**
 * 一次遍历同时产出两份等长文本，行的位置不变（换行原样保留）：
 *   · noComments —— 注释被空格顶掉，字符串字面量原样保留：B 段要在字符串里找档位字面量，但注释里
 *     提到的词不算；
 *   · noStrings —— 注释与字符串内容都被空格顶掉：A 段要数参数个数，串里的逗号与括号不许掺进来。
 */
function scan(src) {
  const n = src.length
  const noComments = src.split('')
  const noStrings = src.split('')
  const blank = (arr, i) => { if (i >= 0 && i < n && arr[i] !== '\n') arr[i] = ' ' }
  let i = 0
  while (i < n) {
    const c = src[i]
    if (c === '/' && src[i + 1] === '/') {
      while (i < n && src[i] !== '\n') { blank(noComments, i); blank(noStrings, i); i += 1 }
      continue
    }
    if (c === '/' && src[i + 1] === '*') {
      blank(noComments, i); blank(noStrings, i); blank(noComments, i + 1); blank(noStrings, i + 1)
      i += 2
      while (i < n && !(src[i] === '*' && src[i + 1] === '/')) { blank(noComments, i); blank(noStrings, i); i += 1 }
      if (i < n) { blank(noComments, i); blank(noStrings, i); blank(noComments, i + 1); blank(noStrings, i + 1); i += 2 }
      continue
    }
    if (c === "'" || c === '"' || c === '\u0060') {
      const quote = c
      blank(noStrings, i)
      i += 1
      while (i < n) {
        const ch = src[i]
        if (ch === '\\') { blank(noStrings, i); blank(noStrings, i + 1); i += 2; continue }
        if (ch === quote) { blank(noStrings, i); i += 1; break }
        blank(noStrings, i)
        i += 1
      }
      continue
    }
    i += 1
  }
  return { noComments: noComments.join(''), noStrings: noStrings.join('') }
}

/** 从 open 处的左括号找到与它配对的右括号；找不到返回 -1。 */
function matchParen(text, open) {
  let depth = 0
  for (let i = open; i < text.length; i++) {
    const c = text[i]
    if (c === '(') depth += 1
    else if (c === ')') { depth -= 1; if (depth === 0) return i }
  }
  return -1
}

/** 从 open 处的左花括号找到与它配对的右花括号（对象字面量取值用）。 */
function matchBrace(text, open) {
  let depth = 0
  for (let i = open; i < text.length; i++) {
    const c = text[i]
    if (c === '{') depth += 1
    else if (c === '}') { depth -= 1; if (depth === 0) return i }
  }
  return -1
}

/** 从 index 处往前找「包含它的那个对象字面量」的左花括号；中间闭合过的嵌套对象跳过。找不到返回 -1。
 *  用途：`ok: false` 只是对象里的一个键，要顺着它往上找到整个失败对象，才能看它有没有带 raw。 */
function enclosingBrace(text, index) {
  let depth = 0
  for (let i = index; i >= 0; i--) {
    const c = text[i]
    if (c === '}') depth += 1
    else if (c === '{') { if (depth === 0) return i; depth -= 1 }
  }
  return -1
}

/** 按最外层逗号切开参数表；串与注释已经被顶掉，括号深度按字符数即可。 */
function splitTop(text) {
  if (text.trim() === '') return []
  const parts = []
  let depth = 0
  let cur = ''
  for (const c of text) {
    if (c === '(' || c === '[' || c === '{') depth += 1
    else if (c === ')' || c === ']' || c === '}') depth -= 1
    if (c === ',' && depth === 0) { parts.push(cur); cur = ''; continue }
    cur += c
  }
  parts.push(cur)
  return parts
}

