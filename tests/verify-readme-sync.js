/*
 * verify-readme-sync.js — 单说明源头契约（#479 最简收口）
 * 用法: node tests/verify-readme-sync.js
 *
 * 契约：package/README.md 必须等于构建管线按同口径从根 README.md 生成的结果。
 * 根 README.md 是唯一源头，发布目录那份禁止手改。手改生成物，本文件报 FAIL。
 * 改说明的正确姿势：改根 README.md，然后跑 node scripts/build.mjs 重新生成。
 * 口径必须与 scripts/build.mjs 的 readmeForNpm 保持一致，改一处必须改另一处。
 */
const fs = require('fs')
const path = require('path')
const ROOT = path.join(__dirname, '..')

const bannerFor = function (version) { return '<!-- AUTO-GENERATED by scripts/build.mjs — DO NOT EDIT. Source: ../README.md @ ' + version + ' -->\n\n' }

function readmeForNpm(rootMd, version, repoUrl) {
  const verNum = String(version).replace(/^v/, '')
  const base = String(repoUrl).replace(/\/$/, '')
  const rawBase = base + '/raw/main/'
  const blobBase = base + '/blob/main/'
  return rootMd
    .split('src="assets/').join('src="' + rawBase + 'assets/')
    .split('](assets/').join('](' + rawBase + 'assets/')
    .split('](docs/').join('](' + blobBase + 'docs/')
    .split('(docs/').join('(' + blobBase + 'docs/')
    .split('1.7.14').join(verNum)
}

let failed = false
const fail = function (msg) { failed = true; console.error('FAIL readme-sync: ' + msg) }

const read = function (p) { return fs.readFileSync(path.join(ROOT, p), 'utf8') }

let pkg = null
try {
  pkg = JSON.parse(read('package/package.json'))
} catch (e) {
  fail('读发布清单失败：' + e.message)
}

if (pkg) {
  const version = 'v' + pkg.version
  const rawRepo = (pkg.repository && pkg.repository.url) || ''
  const repoUrl = String(rawRepo).replace(/^git\+/, '').replace(/\.git$/, '')
  if (!repoUrl) {
    fail('发布清单缺仓库地址，无法推导绝对链接基址')
  } else {
    let rootMd = null
    let actual = null
    try {
      rootMd = read('README.md')
    } catch (e) {
      fail('读根 README.md 失败：' + e.message)
    }
    try {
      actual = read('package/README.md')
    } catch (e) {
      fail('读发布目录 README.md 失败（先跑 node scripts/build.mjs 生成）：' + e.message)
    }
    if (rootMd !== null && actual !== null) {
      const expected = bannerFor(version) + readmeForNpm(rootMd, version, repoUrl)
      if (actual !== expected) {
        fail('发布目录 README.md 与源头不一致。别手改生成物：改根 README.md 后跑 node scripts/build.mjs 重新生成（差异字节数=' + Math.abs(actual.length - expected.length) + '）。')
      }
    }
  }
}

if (!failed) console.log('PASS readme-sync：发布目录说明与根说明同口径一致')
process.exit(failed ? 1 : 0)
